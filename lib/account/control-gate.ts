/**
 * Feature gate дистанционного управления охраной (E12).
 *
 * Модуль без зависимостей: используется и диспетчером источника, и
 * API-маршрутами; smoke-сценарии проверяют парсер изолированно.
 *
 * Правила (жёсткое отключение в E12):
 *  - отсутствие переменной окружения означает ВЫКЛЮЧЕНО;
 *  - включено только значение ровно 'true' (после trim, без учёта регистра);
 *  - любое другое значение ('1', 'yes', 'on', 'TRUE ', 'enabled', …) —
 *    ВЫКЛЮЧЕНО;
 *  - браузер не может повлиять на gate никаким образом: значение читается
 *    только из переменных окружения сервера;
 *  - demo-источник подчиняется тому же gate: обход через демо-данные
 *    запрещён.
 *
 * В рамках E12 gate не включается ни в одном окружении (решение задачи):
 * переменная остаётся незаданной, endpoints возвращают безопасный ответ
 * о недоступности управления и не вызывают write-методы GEORITM.
 */

/** Имя переменной окружения feature gate. */
export const GEORITM_CONTROL_ENV_NAME = 'GEORITM_CONTROL_ENABLED';

/**
 * Парсер значения gate. Выделен для тестирования: единственное
 * включающее значение — 'true' (регистр не важен, пробелы обрезаются).
 */
export const parseControlGate = (value: string | undefined | null): boolean =>
    typeof value === 'string' && value.trim().toLowerCase() === 'true';

/** Feature gate управления охраной: по умолчанию (и в E12 всегда) выключен. */
export const isGeoritmControlEnabled = (): boolean => parseControlGate(process.env[GEORITM_CONTROL_ENV_NAME]);
